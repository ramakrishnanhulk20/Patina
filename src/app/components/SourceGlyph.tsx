export function SourceGlyph({
  id,
  connected = false,
  muted = false,
}: {
  id: SourceId;
  /** Connected sources take the accent, so the logo reads as "the mark". */
  connected?: boolean;
  /** Coming-soon sources sit back, dimmed, until they are real. */
  muted?: boolean;
}) {
  const glyph = GLYPHS[id];

  return (
    <span
      className={`grid h-11 w-11 shrink-0 place-items-center rounded-xl border transition-colors ${
        connected
          ? "border-accent/40 bg-accent-wash text-accent"
          : muted
            ? "border-line bg-panel-2 text-text-4"
            : "border-line bg-panel-2 text-text-2"
      }`}
    >
      {glyph ? (
        <svg viewBox={glyph.viewBox} className="h-5 w-5" fill="currentColor" aria-hidden="true">
          <path d={glyph.path} />
        </svg>
      ) : (
        <span className="text-sm font-semibold uppercase" aria-hidden="true">
          {id.slice(0, 2)}
        </span>
      )}
    </span>
  );
}
